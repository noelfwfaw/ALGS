def _parse_consensus(text):
    """把 OCR 出来的字符串翻译成重复数。返回 None = 这帧不可信，换倍数再读。"""
    if not text:
        return None

    # 正常形态 `2/1`
    if '/' in text:
        head = text.split('/')[0].strip()
        if not head:
            return 0        # 分子是红字 = 不够 = 0 个重复，这是确定答案
        if head.isdigit():
            return int(head)
        return None

    # ❗斜杠经常被认成 `7`：真机三张图实测
    #       2/1 → `271`      3/1 → `371`（原图）或 `3/1`（放大）
    #       1/1 → `74`（原图）或 `174`（放大 3 倍）
    #   所以放宽成「数字 + (7 或 / 或空) + 数字」。
    m = re.match(r'^(\d)\s*[7/]\s*(\d)$', text)
    if m:
        return int(m.group(1))

    # 只读到一个数字（比如放大后只剩分子）
    if len(text) == 1 and text.isdigit():
        return int(text)

    return None


def read_consensus(image):
    """读 `N/1` 的 N（重复获得次数）。读不出来返回 None。

    ❗这块字**只有 8 像素高**。用户 2026-11-06 22:15 的截图量出来：
       `1/1` 落在 **(988,608)-(1012,616)**，压在金色材料图标的下沿上。
       `Ocr.pre_process` 只做二值化、**不放大**，原图经常把分子丢掉。

    实测（三张真值图：1/1、2/1、3/1，参数框 (978,600,1024,624) + threshold=190）：

        原图   x1 → `74`   `271`  `3/1`     ← 1/1 那行连斜杠都没了
        放大 x3 → `174`  `271`  `3/1`      ← 都能解析出正确分子

    OCR 本身很便宜（0.01~0.02 秒），所以先试原图、不行再放大 3 倍，
    两条路都解析不出数字才算失败。原来固定放大 6 倍纯属浪费。
    """
    part = crop(image, CONSENSUS_AREA)
    for scale in (1, 3):
        if scale == 1:
            big = part
        else:
            big = cv2.resize(part, None, fx=scale, fy=scale,
                             interpolation=cv2.INTER_CUBIC)
        text = (CONSENSUS.ocr([big], direct_ocr=True) or '').strip()
        value = _parse_consensus(text)
        if value is not None:
            return value
    return None

