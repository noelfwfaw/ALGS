def main():
    """Write the strings into each language file, keeping every existing key."""
    for lang in LANGS:
        path = os.path.join(ROOT, 'module', 'config', 'i18n', lang + '.json')
        with open(path, encoding='utf-8') as f:
            data = json.load(f)

        written = []
        for group, texts in GROUPS.items():
            for key, value in texts.get(lang, {}).items():
                group_data = data.setdefault(group, {})
                if isinstance(value, dict) and isinstance(group_data.get(key), dict):
                    group_data[key].update(value)
                else:
                    group_data[key] = value
                written.append(f'{group}.{key}')

        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(json.dumps(data, ensure_ascii=False, indent=2))
        print(f'{lang}: {", ".join(written)}')


if __name__ == '__main__':
    main()
